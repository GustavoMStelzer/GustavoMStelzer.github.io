-- Execute somente em um schema de desenvolvimento destinado à demonstração.
-- Dados fictícios produzidos com DUAL; nenhuma tabela corporativa é acessada.
-- O usuário precisa de permissão CREATE PROCEDURE no próprio schema.
-- Se PCK_PORTFOLIO_DEMO já existir, os comandos CREATE falharão, preservando-o.

CREATE PACKAGE PCK_PORTFOLIO_DEMO AS
  PROCEDURE SP_LISTAR(P_SITUACAO IN VARCHAR2, P_RETORNO OUT SYS_REFCURSOR);
  FUNCTION FC_DESCRICAO(P_CODIGO IN NUMBER) RETURN VARCHAR2;
  PROCEDURE SP_VALIDAR(P_CODIGO IN NUMBER);
END PCK_PORTFOLIO_DEMO;
/

CREATE PACKAGE BODY PCK_PORTFOLIO_DEMO AS
  PROCEDURE SP_LISTAR(P_SITUACAO IN VARCHAR2, P_RETORNO OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN P_RETORNO FOR
      SELECT CD_SERVICO, DS_SERVICO, DS_SITUACAO, FL_ATIVO
      FROM (
        SELECT 101 CD_SERVICO, 'Vistoria' DS_SERVICO,
               'PENDENTE' DS_SITUACAO, 'S' FL_ATIVO FROM DUAL
        UNION ALL
        SELECT 102, 'Instalação', 'CONCLUIDO', 'N' FROM DUAL
      )
      WHERE P_SITUACAO IS NULL OR DS_SITUACAO = P_SITUACAO
      ORDER BY CD_SERVICO;
  END SP_LISTAR;

  FUNCTION FC_DESCRICAO(P_CODIGO IN NUMBER) RETURN VARCHAR2 IS
  BEGIN
    RETURN 'Serviço de demonstração ' || TO_CHAR(P_CODIGO);
  END FC_DESCRICAO;

  PROCEDURE SP_VALIDAR(P_CODIGO IN NUMBER) IS
  BEGIN
    IF P_CODIGO IS NULL OR P_CODIGO <= 0 THEN
      RAISE_APPLICATION_ERROR(-20001, 'Informe um código positivo.');
    END IF;
  END SP_VALIDAR;
END PCK_PORTFOLIO_DEMO;
/

-- Conferir a compilação:
SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM USER_ERRORS
WHERE NAME = 'PCK_PORTFOLIO_DEMO'
ORDER BY TYPE, SEQUENCE;
